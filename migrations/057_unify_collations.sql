-- Migration 057: Unify all app table collations to utf8mb4_unicode_ci
-- Root cause: CREATE TABLE statements use CHARSET=utf8mb4 without explicit COLLATE,
-- so tables inherit the server default collation which differs across MariaDB versions
-- (utf8mb4_general_ci on older, utf8mb4_uca1400_ai_ci on MariaDB 10.10+).
-- JOINs/comparisons between tables with different collations throw
-- "Illegal mix of collations" errors.
-- Fix: CONVERT all app tables to utf8mb4 COLLATE utf8mb4_unicode_ci.
-- This migration is safe to run multiple times (CONVERT is idempotent if already correct).

